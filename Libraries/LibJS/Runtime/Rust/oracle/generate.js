function randomDoubles(count) {
    const values = [];
    for (let i = 0; i < count; ++i) {
        switch (randomInt(6)) {
            case 0:
                values.push(randomFiniteDouble());
                break;
            case 1:
                values.push(randomDoubleWithExponent(-30, 80));
                break;
            case 2:
                values.push(randomShortDecimal());
                break;
            case 3:
                values.push(randomSign() * (nextU32() * 2 ** randomInt(40) + randomInt(4) / 4));
                break;
            case 4:
                values.push(randomDoubleWithExponent(-1074 + 52, -1000));
                break;
            default:
                values.push(randomSign() * 2 ** (randomInt(2098) - 1074));
        }
    }
    return values;
}

