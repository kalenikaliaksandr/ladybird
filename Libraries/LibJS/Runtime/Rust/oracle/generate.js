function observeToIntegerOrInfinity(x) {
    // Array.prototype.indexOf converts fromIndex with ToIntegerOrInfinity and then asks HasProperty for that index,
    // counted from the end for negative values. Every double of magnitude 2^53 or more is already an integer.
    if (!Number.isNaN(x) && Math.abs(x) >= 2 ** 53 - 1) return x;
    const length = 2 ** 53 - 1;
    let key = null;
    const proxy = new Proxy(
        {},
        {
            get(target, property) {
                return property === "length" ? length : undefined;
            },
            has(target, property) {
                key = property;
                throw "found";
            },
        }
    );
    try {
        Array.prototype.indexOf.call(proxy, 0, x);
    } catch (error) {
        if (error !== "found") throw error;
    }
    const index = Number(key);
    return x <= -1 ? index - length : index;
}

function observeToIndex(x) {
    // ArrayBuffer's maxByteLength option goes through ToIndex. Values that are too large to reserve report the index
    // in the error message.
    try {
        return new ArrayBuffer(0, { maxByteLength: x }).maxByteLength;
    } catch (error) {
        const match = /^Not enough memory to allocate (\d+) bytes$/.exec(error.message);
        if (match) return Number(match[1]);
        if (error.message !== "Index must be a positive integer no greater than 2^53-1") throw error;
        return null;
    }
}

