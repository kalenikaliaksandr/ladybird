//! Writes the Rust declarations of the embedding ABI for an embedder written in Rust, from the same items that
//! cbindgen writes LibJS/Embedding/ABI.h from. The declarations copy the C types that the exported functions and the
//! JS_ constants name, declare every type that the ABI only passes behind a pointer as an opaque struct, and declare
//! the functions in an extern block. The stubs define every function as one that must never run, for a test binary
//! that does not link LibJS.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use quote::{ToTokens, quote};
use syn::visit_mut::VisitMut;

use crate::embedding_items::EmbeddingItems;

/// The names a type in the ABI can use that are not items of the ABI.
const EXTERNAL_NAMES: &[&str] = &[
    "u8", "u16", "u32", "u64", "usize", "i8", "i16", "i32", "i64", "isize", "f32", "f64", "bool", "core", "ffi", "ptr",
    "c_void", "c_char", "c_int", "c_uint", "c_long", "c_ulong", "Option", "NonNull",
];

const PREAMBLE: &str = "\
// Generated by the libjs_embedding build script from the embedding module of libjs_rust -- DO NOT EDIT

#[allow(unused_imports)]
use core::ffi::{c_char, c_int, c_uint, c_void};
#[allow(unused_imports)]
use core::ptr::NonNull;
";

const STUBS_PREAMBLE: &str = "\
// Generated by the libjs_embedding build script from the embedding module of libjs_rust -- DO NOT EDIT

#[allow(unused_imports)]
use super::*;
";

/// Rewrites every path to an item of the ABI to the item's bare name, and records the names it meets.
struct NameResolver<'a> {
    item_names: &'a BTreeSet<String>,
    met: BTreeSet<String>,
}

impl VisitMut for NameResolver<'_> {
    fn visit_type_path_mut(&mut self, type_path: &mut syn::TypePath) {
        syn::visit_mut::visit_type_path_mut(self, type_path);
        let last = type_path.path.segments.last().expect("a path has a segment").clone();
        let name = last.ident.to_string();
        if self.item_names.contains(&name) {
            type_path.qself = None;
            type_path.path = syn::Path::from(last);
            self.met.insert(name);
            return;
        }
        for segment in &type_path.path.segments {
            let name = segment.ident.to_string();
            assert!(
                EXTERNAL_NAMES.contains(&name.as_str()),
                "the embedding ABI names `{}`, which is neither one of its own items nor a type the Rust declarations \
                 know",
                type_path.to_token_stream()
            );
        }
    }
}

fn is_cfg(attribute: &syn::Attribute) -> bool {
    attribute.path().is_ident("cfg")
}

fn has_c_layout(attributes: &[syn::Attribute]) -> bool {
    attributes.iter().any(|attribute| {
        attribute.path().is_ident("repr")
            && attribute
                .parse_args_with(syn::punctuated::Punctuated::<syn::Ident, syn::Token![,]>::parse_terminated)
                .is_ok_and(|arguments| {
                    arguments.iter().any(|argument| {
                        argument == "C" || argument == "transparent" || argument.to_string().starts_with('u')
                    })
                })
    })
}

/// Keeps the attributes that change what the item is: its cfgs, its representation and its standard derives.
fn retained_attributes(attributes: &[syn::Attribute]) -> Vec<syn::Attribute> {
    const STANDARD_DERIVES: &[&str] = &["Clone", "Copy", "Debug", "Default", "PartialEq", "Eq", "Hash"];
    let mut retained = Vec::new();
    for attribute in attributes {
        if is_cfg(attribute) || attribute.path().is_ident("repr") {
            retained.push(attribute.clone());
        } else if attribute.path().is_ident("derive") {
            let derives = attribute
                .parse_args_with(syn::punctuated::Punctuated::<syn::Path, syn::Token![,]>::parse_terminated)
                .expect("parse a derive");
            let standard: Vec<&syn::Path> = derives
                .iter()
                .filter(|path| {
                    path.get_ident()
                        .is_some_and(|ident| STANDARD_DERIVES.contains(&ident.to_string().as_str()))
                })
                .collect();
            if !standard.is_empty() {
                retained.push(syn::parse_quote!(#[derive(#(#standard),*)]));
            }
        }
    }
    retained
}

fn type_item_name(item: &syn::Item) -> String {
    match item {
        syn::Item::Struct(item) => item.ident.to_string(),
        syn::Item::Enum(item) => item.ident.to_string(),
        syn::Item::Union(item) => item.ident.to_string(),
        syn::Item::Type(item) => item.ident.to_string(),
        _ => unreachable!("only types are type items"),
    }
}

fn opaque_struct(name: &str) -> String {
    let ident = syn::Ident::new(name, proc_macro2::Span::call_site());
    quote! {
        #[allow(clippy::upper_case_acronyms)]
        #[repr(C)]
        pub struct #ident {
            _opaque: [u8; 0],
        }
    }
    .to_string()
}

/// Copies a type item with its paths resolved, or declares it opaque if C only sees it behind a pointer.
fn copy_type_item(item: &syn::Item, resolver: &mut NameResolver<'_>) -> String {
    match item.clone() {
        syn::Item::Struct(mut item) => {
            if !has_c_layout(&item.attrs) {
                return opaque_struct(&item.ident.to_string());
            }
            item.attrs = retained_attributes(&item.attrs);
            for field in &mut item.fields {
                field.attrs.retain(is_cfg);
                resolver.visit_type_mut(&mut field.ty);
            }
            item.into_token_stream().to_string()
        }
        syn::Item::Union(mut item) => {
            item.attrs = retained_attributes(&item.attrs);
            for field in &mut item.fields.named {
                field.attrs.retain(is_cfg);
                resolver.visit_type_mut(&mut field.ty);
            }
            item.into_token_stream().to_string()
        }
        syn::Item::Enum(mut item) => {
            assert!(
                has_c_layout(&item.attrs),
                "the embedding ABI names the enum {}, which has no C representation",
                item.ident
            );
            item.attrs = retained_attributes(&item.attrs);
            for variant in &mut item.variants {
                variant.attrs.retain(is_cfg);
            }
            item.into_token_stream().to_string()
        }
        syn::Item::Type(mut item) => {
            item.attrs.retain(is_cfg);
            resolver.visit_type_mut(&mut item.ty);
            item.into_token_stream().to_string()
        }
        _ => unreachable!("only types are type items"),
    }
}

/// The parameters of a function with their types resolved, named as in the source, or `_` for a pattern.
fn parameters(function: &syn::ItemFn, resolver: &mut NameResolver<'_>, named: bool) -> Vec<proc_macro2::TokenStream> {
    function
        .sig
        .inputs
        .iter()
        .map(|input| {
            let syn::FnArg::Typed(parameter) = input else {
                panic!("{} takes self", function.sig.ident);
            };
            let mut parameter_type = (*parameter.ty).clone();
            resolver.visit_type_mut(&mut parameter_type);
            match (&*parameter.pat, named) {
                (syn::Pat::Ident(pattern), true) => {
                    let name = &pattern.ident;
                    quote!(#name: #parameter_type)
                }
                _ => quote!(_: #parameter_type),
            }
        })
        .collect()
}

pub struct RustAbi {
    pub declarations: String,
    /// Definitions of the functions, in a module that sees the declarations' types.
    pub stubs: String,
}

pub fn generate(items: &EmbeddingItems) -> RustAbi {
    let mut item_names: BTreeSet<String> = items.types.iter().map(type_item_name).collect();
    item_names.extend(items.opaque_types.iter().map(ToString::to_string));
    let mut resolver = NameResolver {
        item_names: &item_names,
        met: BTreeSet::new(),
    };

    let mut functions = String::new();
    let mut stubs = String::from(STUBS_PREAMBLE);
    for function in &items.functions {
        let attributes: Vec<&syn::Attribute> = function.attrs.iter().filter(|attribute| is_cfg(attribute)).collect();
        let name = &function.sig.ident;
        let mut output = function.sig.output.clone();
        if let syn::ReturnType::Type(_, output_type) = &mut output {
            resolver.visit_type_mut(output_type);
        }
        let named_parameters = parameters(function, &mut resolver, true);
        let declaration = quote! {
            #(#attributes)*
            pub fn #name(#(#named_parameters),*) #output;
        };
        let _ = writeln!(functions, "{declaration}");

        let unnamed_parameters = parameters(function, &mut resolver, false);
        let message = format!("{name} is not available without LibJS");
        let stub = quote! {
            #(#attributes)*
            #[unsafe(no_mangle)]
            pub unsafe extern "C" fn #name(#(#unnamed_parameters),*) #output {
                unreachable!(#message)
            }
        };
        let _ = writeln!(stubs, "{stub}");
    }

    let mut constants = String::new();
    for constant in &items.constants {
        let mut constant = constant.clone();
        constant.attrs.retain(is_cfg);
        resolver.visit_type_mut(&mut constant.ty);
        let _ = writeln!(constants, "{}", constant.into_token_stream());
    }

    // Copy every type the functions and constants name, and every type those name in turn.
    let types_by_name: BTreeMap<String, Vec<&syn::Item>> =
        items.types.iter().fold(BTreeMap::new(), |mut types_by_name, item| {
            types_by_name.entry(type_item_name(item)).or_default().push(item);
            types_by_name
        });
    let opaque_names: BTreeSet<String> = items.opaque_types.iter().map(ToString::to_string).collect();
    let mut copied = BTreeSet::new();
    let mut types = String::new();
    loop {
        let pending: Vec<String> = resolver.met.difference(&copied).cloned().collect();
        if pending.is_empty() {
            break;
        }
        for name in pending {
            copied.insert(name.clone());
            if opaque_names.contains(&name) {
                let _ = writeln!(types, "{}", opaque_struct(&name));
                continue;
            }
            for item in &types_by_name[&name] {
                let _ = writeln!(types, "{}", copy_type_item(item, &mut resolver));
            }
        }
    }

    let mut text = String::from(PREAMBLE);
    text.push_str(&types);
    text.push_str(&constants);
    let _ = write!(text, "unsafe extern \"C\" {{\n{functions}}}\n");
    RustAbi {
        declarations: text,
        stubs,
    }
}
