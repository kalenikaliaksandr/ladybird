//! Writes the lists of symbols that the LibJS shared library exports, one in the format of each linker. The library
//! exports its own C++ API and the functions of the embedding ABI. Every other symbol of the runtime stays local, so
//! that a process that links LibJS has exactly one copy of the runtime.

use std::fmt::Write;

/// An ELF version script. The C++ API is every symbol with a C++ name that the library does not hide.
pub fn elf_version_script(functions: &[String]) -> String {
    let mut text =
        String::from("/* Generated by the libjs_rust build script -- DO NOT EDIT */\n{\n    global:\n        _Z*;\n");
    for function in functions {
        let _ = writeln!(text, "        {function};");
    }
    text.push_str("    local:\n        *;\n};\n");
    text
}

/// A Mach-O exported symbols list, whose names have the leading underscore of C symbols.
pub fn mach_o_exported_symbols_list(functions: &[String]) -> String {
    let mut text = String::from("# Generated by the libjs_rust build script -- DO NOT EDIT\n__Z*\n");
    for function in functions {
        let _ = writeln!(text, "_{function}");
    }
    text
}

/// A Windows module-definition file. A DLL also exports every symbol that the C++ API marks for export.
pub fn windows_module_definition(functions: &[String]) -> String {
    let mut text = String::from("; Generated by the libjs_rust build script -- DO NOT EDIT\nEXPORTS\n");
    for function in functions {
        let _ = writeln!(text, "    {function}");
    }
    text
}
